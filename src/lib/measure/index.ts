/**
 * Ratios nu(I) / mu(I) on the 2^k dyadic intervals of [0, 1], where mu is the
 * Lebesgue measure and nu has density g. They approach dnu/dmu = g as k grows.
 */
export function dyadicRatios(
  g: RealFunction,
  k: number,
): { a: number; b: number; ratio: number }[] {
  const cells = 2 ** k;
  return Array.from({ length: cells }, (_, i) => {
    const a = i / cells;
    const b = (i + 1) / cells;
    return { a, b, ratio: integrate(g, a, b, 200) / (b - a) };
  });
}

