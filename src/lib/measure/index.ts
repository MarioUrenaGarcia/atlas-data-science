/* Integration                                                          */
/* ------------------------------------------------------------------ */

/** Midpoint grid on [a, b] with n cells. */
export function midpoints(a: number, b: number, n: number): number[] {
  const h = (b - a) / n;
  return Array.from({ length: n }, (_, i) => a + (i + 0.5) * h);
}

/** Integral of f on [a, b] by the midpoint rule with many cells, as a reference. */
export function integrate(f: RealFunction, a: number, b: number, n = 20000): number {
  const h = (b - a) / n;
  return midpoints(a, b, n).reduce((sum, x) => sum + f(x) * h, 0);
}

/**
 * The n-th standard simple function below f >= 0: f is rounded down to the grid
 * of step 2^-n and capped at n. The sequence increases to f pointwise.
 */
export function simpleApproximation(f: RealFunction, n: number): RealFunction {
  const step = 2 ** -n;
  return (x) => Math.min(n, Math.floor(f(x) / step) * step);
}

/** Lebesgue measure of {x in [a, b] : f(x) > t}, measured on a fine grid. */
export function superLevelMeasure(
  f: RealFunction,
  a: number,
  b: number,
  t: number,
  n = 4000,
): number {
  const h = (b - a) / n;
  return midpoints(a, b, n).filter((x) => f(x) > t).length * h;
}

/**
 * Layer-cake form of the Lebesgue integral of f >= 0: the integral over t of the
 * measure of {f > t}, summed over horizontal slabs of height dt.
 */
export function layerCakeIntegral(
  f: RealFunction,
  a: number,
  b: number,
  top: number,
  slabs = 400,
): number {
  const dt = top / slabs;
  let sum = 0;
  for (let k = 0; k < slabs; k += 1) sum += superLevelMeasure(f, a, b, (k + 0.5) * dt) * dt;
  return sum;
}

