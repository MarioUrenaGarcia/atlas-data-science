/* Lebesgue measure: Cantor set and covers                             */
/* ------------------------------------------------------------------ */

export type Interval = [number, number];

/** Intervals that remain after k steps of removing open middle thirds from [0, 1]. */
export function cantorIntervals(k: number): Interval[] {
  let intervals: Interval[] = [[0, 1]];
  for (let step = 0; step < k; step += 1) {
    intervals = intervals.flatMap(([a, b]) => {
      const third = (b - a) / 3;
      return [
        [a, a + third],
        [b - third, b],
      ] as Interval[];
    });
  }
  return intervals;
}

export const totalLength = (intervals: readonly Interval[]) =>
  intervals.reduce((sum, [a, b]) => sum + (b - a), 0);

/** The rationals of [0, 1] listed by denominator: 0, 1, 1/2, 1/3, 2/3, 1/4, 3/4, ... */
export function enumerateRationals(count: number): { p: number; q: number; value: number }[] {
  const out: { p: number; q: number; value: number }[] = [];
  const seen = new Set<number>();
  for (let q = 1; out.length < count; q += 1) {
    for (let p = 0; p <= q && out.length < count; p += 1) {
      const value = p / q;
      const key = Math.round(value * 1e12);
      if (seen.has(key)) continue;
      seen.add(key);
      out.push({ p, q, value });
    }
  }
  return out;
}

/**
 * Cover of the first `count` rationals of [0, 1] by intervals of lengths
 * epsilon/2, epsilon/4, ...: the total length stays below epsilon however many
 * rationals are covered, which is why the rationals have measure zero.
 */
export function rationalCover(count: number, epsilon: number) {
  return enumerateRationals(count).map((r, k) => {
    const length = epsilon / 2 ** (k + 1);
    return { ...r, interval: [r.value - length / 2, r.value + length / 2] as Interval, length };
  });
}

