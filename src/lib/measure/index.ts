/** Union of the intervals of [a, b] where pred holds, found on a grid of n cells. */
export function regionWhere(
  pred: (x: number) => boolean,
  a: number,
  b: number,
  n = 2000,
): [number, number][] {
  const h = (b - a) / n;
  const out: [number, number][] = [];
  let start: number | null = null;
  for (let i = 0; i < n; i += 1) {
    const inside = pred(a + (i + 0.5) * h);
    if (inside && start === null) start = a + i * h;
    if (!inside && start !== null) {
      out.push([start, a + i * h]);
      start = null;
    }
  }
  if (start !== null) out.push([start, b]);
  return out;
}

