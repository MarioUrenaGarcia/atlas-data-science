/** Lp norm of a vector, with p = Infinity for the maximum norm. */
export function lpNorm(values: readonly number[], p: number): number {
  if (!Number.isFinite(p)) return Math.max(...values.map(Math.abs));
  return values.reduce((s, v) => s + Math.abs(v) ** p, 0) ** (1 / p);
}

/** Lp norm of a function on [a, b], computed on a midpoint grid. */
export function functionLpNorm(f: RealFunction, a: number, b: number, p: number, n = 4000): number {
  const xs = midpoints(a, b, n);
  if (!Number.isFinite(p)) return Math.max(...xs.map((x) => Math.abs(f(x))));
  const h = (b - a) / n;
  return xs.reduce((s, x) => s + Math.abs(f(x)) ** p * h, 0) ** (1 / p);
}

/** Point of the unit sphere of the Lp norm in the plane in the direction of angle theta. */
export function lpUnitCirclePoint(theta: number, p: number): [number, number] {
  const c = Math.cos(theta);
  const s = Math.sin(theta);
  const r = 1 / lpNorm([c, s], p);
  return [r * c, r * s];
}
