/* Sigma-algebras on a finite set                                      */
/* ------------------------------------------------------------------ */

/** Elements of a subset of {0, ..., n - 1} written as a bit mask. */
export function members(mask: number, n: number): number[] {
  return Array.from({ length: n }, (_, i) => i).filter((i) => (mask >> i) & 1);
}

export interface SigmaRound {
  /** Sets present after this round, as sorted bit masks. */
  sets: number[];
  /** Sets that this round added. */
  added: number[];
}

/**
 * Sigma-algebra generated by the given sets on a universe of n points, built
 * by rounds: each round adds the complements and pairwise unions of what is
 * already there. On a finite set countable unions reduce to finite ones, so
 * the process stops when a round adds nothing.
 */
export function generateSigmaAlgebra(n: number, generators: readonly number[]): SigmaRound[] {
  const full = (1 << n) - 1;
  let current = new Set<number>([0, full, ...generators.map((g) => g & full)]);
  const rounds: SigmaRound[] = [{ sets: [...current].sort((a, b) => a - b), added: [...current] }];
  for (;;) {
    const next = new Set(current);
    for (const a of current) {
      next.add(full & ~a);
      for (const b of current) next.add(a | b);
    }
    const added = [...next].filter((s) => !current.has(s));
    if (added.length === 0) break;
    current = next;
    rounds.push({ sets: [...current].sort((a, b) => a - b), added });
  }
  return rounds;
}

/** Atoms of a finite sigma-algebra: its minimal non-empty sets, which partition the universe. */
export function atoms(sets: readonly number[]): number[] {
  const nonEmpty = sets.filter((s) => s !== 0);
  return nonEmpty.filter((s) => !nonEmpty.some((t) => t !== s && (t & s) === t));
}

/** Whether a family of masks is closed under complement and union. */
export function isSigmaAlgebra(n: number, sets: readonly number[]): boolean {
  const full = (1 << n) - 1;
  const family = new Set(sets);
  if (!family.has(0) || !family.has(full)) return false;
  for (const a of family) {
    if (!family.has(full & ~a)) return false;
    for (const b of family) if (!family.has(a | b)) return false;
  }
  return true;
}

